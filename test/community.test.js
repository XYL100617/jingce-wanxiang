'use strict';

const test = require('node:test');
const assert = require('node:assert/strict');
const fs = require('node:fs');
const os = require('node:os');
const path = require('node:path');
const { createCommunity } = require('../server/community');

test('route DNA community respects sharing consent, checks routes, persists likes/favorites/checkins and public profiles', t => {
  const directory = fs.mkdtempSync(path.join(os.tmpdir(), 'jingce-community-'));
  t.after(() => fs.rmSync(directory, { recursive: true, force: true }));
  const file = path.join(directory, 'community.json');
  let tick = 0;
  const community = createCommunity({ file, now: () => `2026-10-29T10:0${tick++}:00.000Z` });
  const owner = { id: 'owner-1', username: 'route_owner', displayName: '路线作者', consent: { sharing: false } };
  assert.throws(() => community.publishRoute(owner, { title: '文化路线', stops: ['a', 'b'] }, 'g1', () => ({ valid: true })), /开启路线公开分享/);
  owner.consent.sharing = true;
  assert.throws(() => community.publishRoute(owner, { title: '文化路线', stops: ['a', 'b'], tags: ['文化'] }, 'g1', () => ({ valid: false, error: '路网不可达' })), /路网不可达/);
  assert.throws(() => community.publishRoute(owner, { title: '标签错误', stops: ['a', 'b'], tags: ['避晒'] }, 'g1', () => ({ valid: true })), /路线特点须从以下标签/);
  const route = community.publishRoute(owner, { title: '文化慢游', description: '适合慢慢看', stops: ['museum', 'market'], tags: ['文化'] }, 'g1', () => ({ valid: true }));
  assert.equal(route.likes, 0);
  assert.deepEqual(community.listRoutes(null, () => true, { tags: ['文化'] }).map(item => item.id), [route.id]);
  assert.deepEqual(community.listRoutes(null, () => true, { tags: ['亲子'] }), []);
  assert.deepEqual(community.popularPois(new Map([['museum', '大宋武馆']])), []);
  const fan = { id: 'fan-1', username: 'route_fan', displayName: '收藏游客', consent: { sharing: true } };
  assert.equal(community.toggleLike(fan, route.id).likes, 1);
  assert.equal(community.me(owner).stats.likes_received, 1, 'route author sees the received like count in their profile stats');
  community.setMembership(fan, 'favorite_routes', route.id, true);
  const seed = require('../server/dna-seeds').routeSeeds[0];
  community.setSeedMembership(fan, 'liked_routes', seed.id, true);
  community.setSeedMembership(fan, 'favorite_routes', seed.id, true);
  assert.deepEqual(community.seedSummary(seed, fan.id), { ...seed, likes: 1, favorites: 1, liked: true, saved: true });
  community.setMembership(fan, 'favorite_pois', 'museum', true);
  community.setMembership(fan, 'liked_pois', 'museum', true);
  assert.deepEqual(community.popularPois(new Map([['museum', '大宋武馆']]), fan.id)[0], { node_id: 'museum', name: '大宋武馆', favorites: 1, likes: 1, liked: true, saved: true });
  community.setMembership(fan, 'liked_pois', 'museum', false);
  community.setMembership(fan, 'favorite_pois', 'museum', false);
  assert.deepEqual(community.popularPois(new Map([['museum', '大宋武馆']])), []);
  community.setMembership(fan, 'favorite_pois', 'museum', true);
  community.setMembership(fan, 'liked_pois', 'museum', true);
  const checkin = community.checkin(fan, 'museum', '大宋武馆');
  assert.equal(checkin.mode, 'visitor_self_reported_demo');
  assert.equal(community.checkin(fan, 'museum', '大宋武馆').id, checkin.id, 'the same point is not double-counted in one day');
  community.recordView(fan, 'market', '非遗市集');
  community.recordView(fan, 'museum', '大宋武馆');
  community.recordView(fan, 'market', '非遗市集');
  assert.deepEqual(community.me(fan).recent_views.map(item => item.node_id), ['market', 'museum'], 'recent POI browsing is deduplicated and most recent first');
  assert.deepEqual(community.me(fan).stats, { favorite_pois: 1, liked_pois: 1, favorite_routes: 2, liked_routes: 2, published_routes: 0, likes_received: 0 });
  assert.deepEqual(community.me(fan).liked_pois, ['museum']);
  const sharedProfile = community.publicProfile('route_owner', name => name === owner.username ? owner : null);
  assert.equal(sharedProfile.routes[0].id, route.id);
  assert.deepEqual(sharedProfile.stats, { published_routes: 1, likes_received: 1, favorites_received: 1 });
  assert.throws(() => community.publicProfile('private', () => ({ ...owner, consent: { sharing: false } })), /未公开/);
  owner.consent.sharing = false;
  assert.deepEqual(community.listRoutes(null, username => username === owner.username && owner.consent.sharing), [], 'revoking share consent removes published routes from public listings');
  owner.consent.sharing = true;
  assert.equal(community.moderateRoute(route.id, 'hidden').status, 'hidden');
  assert.deepEqual(community.listRoutes(), [], 'hidden routes do not appear in public listings');
  assert.equal(community.listForModeration()[0].status, 'hidden');
  assert.equal(community.moderateRoute(route.id, 'published').status, 'published');

  const reopened = createCommunity({ file });
  assert.equal(reopened.listRoutes()[0].likes, 1);
  assert.equal(reopened.me(fan).favorite_routes[0], route.id);
  assert.ok(reopened.me(fan).liked_routes.includes(seed.id));
  assert.equal(reopened.seedSummary(seed, fan.id).favorites, 1);
  assert.equal(reopened.me(fan).checkins[0].node_id, 'museum');
  assert.equal(reopened.me(fan).recent_views[0].node_id, 'market');
});
